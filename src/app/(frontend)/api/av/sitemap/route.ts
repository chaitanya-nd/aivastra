import { blockedResponse } from '@/lib/crawl-guard'
import { getClient } from '@/lib/data'
import { mediaUrl } from '@/lib/seo'
import { authorSitemapOn, collect, SOURCES } from '@/lib/sitemap'
import { absoluteUrl, getPath, SITE_URL } from '@/lib/urls'

export const dynamic = 'force-dynamic'

/**
 * Rank Math-style sitemaps: /sitemap_index.xml + /post-sitemap.xml, /page-sitemap2.xml … (rewritten in next.config.mjs).
 * Same markup as the WordPress site: styled in the browser by /main-sitemap.xsl, ISO dates with +00:00, image:image
 * per content image. Open to everyone, as on WordPress; while search engines are blocked the files also say noindex
 * and robots.txt keeps crawlers out.
 */
const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')
const iso = (d?: string | null) => (d ? `${new Date(d).toISOString().slice(0, 19)}+00:00` : '')
const HEAD = '<?xml version="1.0" encoding="UTF-8"?><?xml-stylesheet type="text/xsl" href="/main-sitemap.xsl"?>\n'
const FOOT = '\n<!-- XML Sitemap generated by AI Vastra -->'
const URLSET = '<urlset xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:image="http://www.google.com/schemas/sitemap-image/1.1" xsi:schemaLocation="http://www.sitemaps.org/schemas/sitemap/0.9 http://www.sitemaps.org/schemas/sitemap/0.9/sitemap.xsd http://www.google.com/schemas/sitemap-image/1.1 http://www.google.com/schemas/sitemap-image/1.1/sitemap-image.xsd" xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
const xmlRes = (body: string) => new Response(HEAD + body + FOOT, { headers: { 'Content-Type': 'text/xml; charset=UTF-8', 'X-Robots-Tag': 'noindex', 'Cache-Control': 'no-cache, no-store, must-revalidate, max-age=0' } })
const urlXml = (loc: string, lastmod?: string, extra = '') => `\t<url>\n\t\t<loc>${esc(loc)}</loc>\n${lastmod ? `\t\t<lastmod>${iso(lastmod)}</lastmod>\n` : ''}${extra}\t</url>\n`
const urlset = (urls: string, ns = '') => xmlRes(`${URLSET.replace('<urlset', `<urlset${ns}`)}\n${urls}</urlset>`)

export async function GET(req: Request) {
  const res = await serve(req)
  if (await blockedResponse()) res.headers.set('X-Robots-Tag', 'noindex, nofollow')
  return res
}

async function serve(req: Request): Promise<Response> {
  const name = new URL(req.url).pathname.split('/').pop() || ''
  const file = /-sitemap\d*\.xml$/.test(name) ? name : 'index' // rewrites keep the public URL in req.url
  const payload = await getClient()
  const [ps, settings]: any[] = await Promise.all([payload.findGlobal({ slug: 'plugin-settings', depth: 0 }), payload.findGlobal({ slug: 'site-settings', depth: 0 })])
  if (ps?.sitemapEnabled === false) return new Response('Sitemap disabled', { status: 404 })
  const max = Math.max(1, Number(ps?.sitemapMaxLinks) || 200)

  if (file === 'index') {
    const items: string[] = []
    for (const src of SOURCES) {
      const e = (await collect(src, settings, ps)).rows
      const n = Math.ceil(e.length / max)
      for (let i = 1; i <= n; i++) {
        const last = e.slice((i - 1) * max, i * max).map((x) => x.lastmod).filter(Boolean).sort().at(-1)
        items.push(`\t<sitemap>\n\t\t<loc>${SITE_URL}/${src.key}-sitemap${i > 1 ? i : ''}.xml</loc>\n${last ? `\t\t<lastmod>${iso(last)}</lastmod>\n` : ''}\t</sitemap>\n`)
      }
    }
    if (authorSitemapOn(ps)) items.push(`\t<sitemap>\n\t\t<loc>${SITE_URL}/author-sitemap.xml</loc>\n\t</sitemap>\n`)
    for (const key of ['news', 'video'] as const) if (ps?.[`${key}Sitemap`]) items.push(`\t<sitemap>\n\t\t<loc>${SITE_URL}/${key}-sitemap.xml</loc>\n\t</sitemap>\n`)
    return xmlRes(`<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${items.join('')}</sitemapindex>`)
  }
  if (file === 'news-sitemap.xml' && ps?.newsSitemap) return newsSitemap(ps)
  if (file === 'video-sitemap.xml' && ps?.videoSitemap) return videoSitemap()
  if (file === 'author-sitemap.xml' && authorSitemapOn(ps)) return authorSitemap()
  const m = file.match(/^([a-z_]+)-sitemap(\d*)\.xml$/)
  const src = m && SOURCES.find((s) => s.key === m[1])
  if (!m || !src || m[2] === '1') return new Response('Not found', { status: 404 })
  const page = Number(m[2] || 1)
  const e = (await collect(src, settings, ps)).rows.slice((page - 1) * max, page * max)
  if (!e.length) return new Response('Not found', { status: 404 })
  return urlset(e.map((x) => urlXml(x.loc, x.lastmod, x.images.map((im) => `\t\t<image:image>\n\t\t\t<image:loc>${esc(im)}</image:loc>\n\t\t</image:image>\n`).join(''))).join(''))
}

const published = { _status: { equals: 'published' } }
const visible = (d: any) => !d.meta?.noindex && (d.visibility ?? 'public') === 'public'

/** Google News sitemap: posts published in the last 48 hours. */
async function newsSitemap(ps: any) {
  const payload = await getClient()
  const since = new Date(Date.now() - 48 * 3600_000).toISOString()
  const res = await payload.find({ collection: 'posts', where: { and: [published, { publishedAt: { greater_than: since } }] }, limit: 1000, depth: 0, pagination: false, overrideAccess: true })
  const name = esc(ps?.newsPublicationName || 'AI Vastra')
  const urls = (res.docs as any[]).filter(visible).map((d) => `\t<url>\n\t\t<loc>${esc(absoluteUrl(getPath('posts', d)))}</loc>\n\t\t<news:news><news:publication><news:name>${name}</news:name><news:language>en</news:language></news:publication><news:publication_date>${new Date(d.publishedAt).toISOString()}</news:publication_date><news:title>${esc(d.title)}</news:title></news:news>\n\t</url>\n`).join('')
  return urlset(urls, ' xmlns:news="http://www.google.com/schemas/sitemap-news/0.9"')
}

const YT = /(?:youtube\.com\/(?:embed\/|watch\?v=)|youtu\.be\/)([\w-]{11})/
const VIMEO = /(?:player\.)?vimeo\.com\/(?:video\/)?(\d+)/

/** Video sitemap: posts embedding YouTube / Vimeo, or with a Video schema. */
async function videoSitemap() {
  const payload = await getClient()
  const out: string[] = []
  for (const coll of ['posts', 'guides', 'cases', 'updates', 'reviews'] as const) {
    const res = await payload.find({ collection: coll, where: published, limit: 5000, depth: 0, pagination: false, overrideAccess: true })
    for (const d of (res.docs as any[]).filter(visible)) {
      const html = String(d.contentHtml || '')
      const sd = d.meta?.schemaType === 'VideoObject' ? d.meta?.schemaData || {} : null
      const yt = html.match(YT)?.[1], vm = html.match(VIMEO)?.[1]
      const player = sd?.videoUrl || (yt ? `https://www.youtube.com/embed/${yt}` : vm ? `https://player.vimeo.com/video/${vm}` : '')
      if (!player) continue
      const thumb = sd?.thumbnailUrl || (yt ? `https://i.ytimg.com/vi/${yt}/hqdefault.jpg` : mediaUrl(d.featuredImage) || d.featuredImageUrl)
      if (!thumb) continue
      const desc = (sd?.description || d.meta?.description || d.excerpt || d.title || '').slice(0, 2000)
      out.push(`\t<url>\n\t\t<loc>${esc(absoluteUrl(getPath(coll, d)))}</loc>\n\t\t<video:video><video:thumbnail_loc>${esc(thumb)}</video:thumbnail_loc><video:title>${esc(sd?.name || d.title)}</video:title><video:description>${esc(desc)}</video:description><video:player_loc>${esc(player)}</video:player_loc>${sd?.uploadDate || d.publishedAt ? `<video:publication_date>${new Date(sd?.uploadDate || d.publishedAt).toISOString()}</video:publication_date>` : ''}</video:video>\n\t</url>\n`)
    }
  }
  return urlset(out.join(''), ' xmlns:video="http://www.google.com/schemas/sitemap-video/1.1"')
}

/** Author archives that have at least one published post. */
async function authorSitemap() {
  const payload = await getClient()
  const users = await payload.find({ collection: 'users', depth: 0, pagination: false, limit: 500, overrideAccess: true, where: { slug: { exists: true } } })
  const out: string[] = []
  for (const u of users.docs as any[]) {
    if (!u.slug || u.role === 'subscriber') continue
    const last = await payload.find({ collection: 'posts', where: { and: [published, { author: { equals: u.id } }] }, sort: '-modifiedAt', limit: 1, depth: 0, overrideAccess: true })
    if (!last.totalDocs) continue
    const lm = (last.docs[0] as any)?.modifiedAt || (last.docs[0] as any)?.updatedAt
    out.push(urlXml(`${SITE_URL}/author/${u.slug}/`, lm))
  }
  return urlset(out.join(''))
}
